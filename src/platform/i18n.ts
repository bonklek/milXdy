const MESSAGES_BY_LOCALE: Partial<Record<MilxdyLocale, Record<string, string>>> = {
  ru: RU_MESSAGES,
  es: ES_MESSAGES,
  ja: JA_MESSAGES,
};

const EXACT_TEXT_BY_LOCALE: Partial<Record<MilxdyLocale, Record<string, string>>> = {
  ru: RU_EXACT_TEXT,
  es: ES_EXACT_TEXT,
  ja: JA_EXACT_TEXT,
};

let activeLocale: MilxdyLocale = detectSystemLocale();
let activePreference: MilxdyLocalePreference = "auto";

export async function initializeLocalization(): Promise<MilxdyLocale> {
  const stored = await chrome.storage.local.get({ [LOCALE_STORAGE_KEY]: "auto" }).catch(() => ({ [LOCALE_STORAGE_KEY]: "auto" }));
  activePreference = normalizeLocalePreference(stored[LOCALE_STORAGE_KEY]);
  activeLocale = resolveLocale(activePreference);
  return activeLocale;
}

export function currentLocale(): MilxdyLocale {
  return activeLocale;
}

export function currentLocalePreference(): MilxdyLocalePreference {
  return activePreference;
}

export async function setLocalePreference(preference: MilxdyLocalePreference): Promise<MilxdyLocale> {
  activePreference = normalizeLocalePreference(preference);
  activeLocale = resolveLocale(activePreference);
  await chrome.storage.local.set({ [LOCALE_STORAGE_KEY]: activePreference });
  return activeLocale;
}

export function observeLocalizationChanges(callback: (locale: MilxdyLocale) => void): () => void {
  const listener = (changes: Record<string, chrome.storage.StorageChange>, area: string) => {
    if (area !== "local" || !changes[LOCALE_STORAGE_KEY]) return;
    activePreference = normalizeLocalePreference(changes[LOCALE_STORAGE_KEY].newValue);
    activeLocale = resolveLocale(activePreference);
    callback(activeLocale);
  };
  chrome.storage.onChanged.addListener(listener);
  return () => chrome.storage.onChanged.removeListener(listener);
}

export function t(key: string, fallback: string, substitutions: readonly (string | number)[] = []): string {
  const template = MESSAGES_BY_LOCALE[activeLocale]?.[key] || fallback;
  return substitutions.reduce<string>(
    (text, value, index) => text.replaceAll(`$${index + 1}`, String(value)),
    template,
  );
}

export function tx(fallback: string): string {
  return EXACT_TEXT_BY_LOCALE[activeLocale]?.[fallback] || fallback;
}

export function applyDocumentLocale(documentRef: Document = document, options: { setLang?: boolean } = {}): void {
  const root = documentRef.documentElement;
  if (options.setLang !== false) root.lang = activeLocale;
  root.dataset.milxdyLocale = activeLocale;
  root.dataset.milxdyLocaleScript = localeScript(activeLocale);
}

export function applyLocalizedDom(root: ParentNode = document): void {
  const elements = root.querySelectorAll<HTMLElement>("[data-i18n]");
  for (const element of Array.from(elements)) {
    const key = element.dataset.i18n;
    if (!key) continue;
    const fallback = element.dataset.i18nFallback ?? element.textContent ?? key;
    element.textContent = t(key, fallback);
  }
  applyLocalizedAttribute(root, "data-i18n-title", "title");
  applyLocalizedAttribute(root, "data-i18n-aria-label", "aria-label");
  applyLocalizedAttribute(root, "data-i18n-placeholder", "placeholder");
  applyExactTextLocalization(root);
  applyExactAttributeLocalization(root, "title");
  applyExactAttributeLocalization(root, "aria-label");
  applyExactAttributeLocalization(root, "placeholder");
}

export function normalizeLocalePreference(value: unknown): MilxdyLocalePreference {
  return value === "ru" || value === "en" || value === "es" || value === "ja" || value === "auto" ? value : "auto";
}

function applyLocalizedAttribute(root: ParentNode, dataAttribute: string, targetAttribute: string): void {
  const elements = root.querySelectorAll<HTMLElement>(`[${dataAttribute}]`);
  for (const element of Array.from(elements)) {
    const key = element.getAttribute(dataAttribute);
    if (!key) continue;
    const fallback = element.getAttribute(`${dataAttribute}-fallback`)
      ?? element.getAttribute(targetAttribute)
      ?? key;
    element.setAttribute(targetAttribute, t(key, fallback));
  }
}

function applyExactTextLocalization(root: ParentNode): void {
  if (!EXACT_TEXT_BY_LOCALE[activeLocale]) return;
  const ownerDocument = root instanceof Document ? root : root instanceof Element ? root.ownerDocument : document;
  const walker = ownerDocument.createTreeWalker(root as Node, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const textNode = node as Text;
      const parent = textNode.parentElement;
      if (!parent || !textNode.textContent?.trim()) return NodeFilter.FILTER_REJECT;
      if (parent.closest("script, style, textarea, [data-i18n], [data-no-i18n]")) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    },
  });
  const nodes: Text[] = [];
  while (walker.nextNode()) nodes.push(walker.currentNode as Text);
  for (const node of nodes) {
    const value = node.textContent ?? "";
    const trimmed = value.trim();
    const translated = tx(trimmed);
    if (translated === trimmed) continue;
    const leading = value.match(/^\s*/)?.[0] ?? "";
    const trailing = value.match(/\s*$/)?.[0] ?? "";
    node.textContent = `${leading}${translated}${trailing}`;
  }
}

function applyExactAttributeLocalization(root: ParentNode, attribute: "title" | "aria-label" | "placeholder"): void {
  if (!EXACT_TEXT_BY_LOCALE[activeLocale]) return;
  const elements = root.querySelectorAll<HTMLElement>(`[${attribute}]`);
  for (const element of Array.from(elements)) {
    const value = element.getAttribute(attribute);
    if (!value) continue;
    const translated = tx(value);
    if (translated !== value) element.setAttribute(attribute, translated);
  }
}

function resolveLocale(preference: MilxdyLocalePreference): MilxdyLocale {
  return preference === "auto" ? detectSystemLocale() : preference;
}

function detectSystemLocale(): MilxdyLocale {
  const candidates = [
    chrome.i18n?.getUILanguage?.(),
    ...Array.from(navigator.languages || []),
    navigator.language,
  ];
  for (const candidate of candidates) {
    if (typeof candidate !== "string") continue;
    const language = candidate.toLowerCase().split("-")[0];
    if (language === "ru" || language === "es" || language === "ja") return language;
  }
  return "en";
}

function localeScript(locale: MilxdyLocale): "latin" | "cyrillic" | "cjk" {
  if (locale === "ru") return "cyrillic";
  if (locale === "ja") return "cjk";
  return "latin";
}
